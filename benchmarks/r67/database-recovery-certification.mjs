import assert from 'node:assert/strict';
import net from 'node:net';
import { writeFile } from 'node:fs/promises';
import { SQLiteCloudDatabase } from '@codeforge/cloud-db';
import { HostedAdmissionAuthority, HostedQueueWorker } from '@codeforge/cloud-gateway';

const delay = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
const db = new SQLiteCloudDatabase();
const user = await db.createUser({ displayName: 'R67 isolated database certification', primaryIdentity: `r67-cert-db:${Date.now()}` });
const route = { providerId: 'synthetic-no-inference', modelId: 'free-test' };
await db.setHostedProviderCapacity({ ...route, maxConcurrent: 1 });
const authority = new HostedAdmissionAuthority({ db, workerId: 'r67-isolated-before-restart', leaseMs: 200, maxUserConcurrent: 1 });
const restarted = new HostedAdmissionAuthority({ db, workerId: 'r67-isolated-after-restart', leaseMs: 200, maxUserConcurrent: 1 });
const output = { startedAt: new Date().toISOString(), status: 'RUNNING', evidenceClass: 'PRODUCTION_HOSTED_QUEUE_AND_ADMISSION_CODE_PATH_ISOLATED_SQLITE_REAL_LOOPBACK_FAULT', productionPostgresOutage: 'NOT_TESTED', cases: [], inferenceDispatched: false, spendEvidence: 'No inference is dispatched in this queue certification; inference/accounting idempotency is separately certified.' };
const params = id => ({ executionId: id, idempotencyKey: id, userId: user.id, taskId: id, ...route });
const server = net.createServer(socket => socket.end('ready'));
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const port = server.address().port;
await new Promise(resolve => server.close(resolve));
const attempts = [], errors = [];
const realClaim = authority.claim.bind(authority);
authority.claim = async () => {
  attempts.push(performance.now());
  await new Promise((resolve, reject) => {
    const socket = net.createConnection({ host: '127.0.0.1', port });
    socket.setTimeout(500, () => socket.destroy(new Error('DB_CONNECT_TIMEOUT')));
    socket.once('connect', () => { socket.end(); resolve(); });
    socket.once('error', reject);
  });
  return realClaim();
};
let executions = 0;
const queued = await authority.enqueue(params('r67-queued-during-db-outage'));
const duplicate = await authority.enqueue({ ...params('r67-queued-during-db-outage'), executionId: 'r67-duplicate-request' });
assert.equal(duplicate.execution.id, queued.execution.id);
assert.equal(duplicate.created, false);
const worker = new HostedQueueWorker({ authority, idleWaitMs: 200, heartbeatMs: 50, execute: async () => { executions++; return { status: 'completed' }; }, onError: error => errors.push({ at: performance.now(), code: error.code, message: error.message }) });
const running = worker.run();
await delay(1200);
assert.equal((await authority.get(queued.execution.id, user.id)).status, 'queued');
assert.equal(executions, 0);
await new Promise(resolve => server.listen(port, '127.0.0.1', resolve));
for (let attempt = 0; attempt < 100 && (await authority.get(queued.execution.id, user.id)).status !== 'completed'; attempt++) await delay(50);
worker.stop(); await running;
const completed = await authority.get(queued.execution.id, user.id);
assert.equal(completed.status, 'completed'); assert.equal(executions, 1);
const retryIntervalsMs = attempts.slice(1).map((time, index) => time - attempts[index]).slice(0, errors.length - 1);
assert.ok(retryIntervalsMs.every(interval => interval >= 180));
assert.equal((await authority.metrics()).activeReservations, 0);
output.cases.push({ name: 'Queued claim survives connectivity outage and duplicate enqueue', status: 'PASS', terminal: completed.status, executions, duplicateEnqueueCreated: duplicate.created, errors, retryIntervalsMs, activeReservations: 0 });

await restarted.enqueue(params('r67-claimed-before-restart'));
const claim = await restarted.claim(); assert.ok(claim);
await delay(250);
const fresh = new HostedAdmissionAuthority({ db, workerId: 'r67-isolated-reconciler', leaseMs: 200 });
const reconciliation = await fresh.reconcile(); assert.equal(reconciliation.recovered, 1);
let recoveredExecutions = 0;
const resumed = new HostedQueueWorker({ authority: fresh, execute: async () => { recoveredExecutions++; return { status: 'completed' }; } });
await resumed.runOnce(); resumed.stop();
assert.equal((await fresh.get('r67-claimed-before-restart', user.id)).status, 'completed');
assert.equal(recoveredExecutions, 1); assert.equal((await fresh.metrics()).activeReservations, 0);
output.cases.push({ name: 'Restart before dispatch releases expired fenced claim and executes once', status: 'PASS', reconciliation, executions: recoveredExecutions, activeReservations: 0 });

await fresh.enqueue(params('r67-ambiguous-after-dispatch'));
const ambiguous = await fresh.claim(); assert.ok(ambiguous);
await fresh.beginDispatch(ambiguous.execution.id, ambiguous.lease.id);
await delay(250); await restarted.reconcile();
assert.equal((await restarted.get(ambiguous.execution.id, user.id)).status, 'recovery_pending');
assert.equal(await restarted.claim(), undefined);
const resolution = await restarted.resolveRecoveryPending(ambiguous.execution.id, 'R67 ambiguous dispatch: revalidation required', 'failed');
assert.equal(resolution.execution.status, 'failed');
assert.equal((await restarted.metrics()).activeReservations, 0);
output.cases.push({ name: 'Ambiguous dispatched claim is not replayed after restart', status: 'PASS', terminal: resolution.execution.status, duplicateExecution: 0, activeReservations: 0 });

await restarted.enqueue(params('r67-permanent-execution-db-failure'));
let permanentExecutions = 0;
const permanent = new HostedQueueWorker({ authority: restarted, execute: async () => { permanentExecutions++; throw new Error('DB_PERMANENT_FAILURE: isolated operation cannot reconnect'); } });
await permanent.runOnce(); permanent.stop();
const failed = await restarted.get('r67-permanent-execution-db-failure', user.id);
assert.equal(failed.status, 'failed'); assert.match(failed.resultError, /DB_PERMANENT_FAILURE/);
assert.equal(permanentExecutions, 1); assert.equal((await restarted.metrics()).activeReservations, 0);
output.cases.push({ name: 'Permanent dispatched operation failure is terminal and observable', status: 'PASS', terminal: failed.status, resultError: failed.resultError, executions: permanentExecutions, activeReservations: 0 });
await new Promise(resolve => server.close(resolve)); await db.close();
output.finishedAt = new Date().toISOString(); output.status = 'PASS';
output.limitations = ['Real ECONNREFUSED is injected before the isolated SQLite claim authority. No production Postgres connection is interrupted.', 'Permanent claim-store failure remains queued with observable bounded errors until the worker stops; it is never mislabeled completed. Permanent dispatched operation failure is independently shown as terminal failed.', 'The restarted authorities share durable database state but this harness does not kill its operating system process; actual parent process/server kills are certified separately.'];
await writeFile('docs/evidence/r67-everyday-completion-reliability/R67-DATABASE-RECOVERY-CERTIFICATION.json', `${JSON.stringify(output, null, 2)}\n`);
console.log(JSON.stringify({ status: output.status, cases: output.cases.length }));
